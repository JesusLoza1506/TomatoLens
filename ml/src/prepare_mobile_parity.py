"""Generate an Android-only Flutter test from the reference sample vectors."""

import argparse
import base64
import json
from pathlib import Path

from common import ROOT, sha256
from experiment import read_json


HEADER = """// Generated by ml/src/prepare_mobile_parity.py; only included in the test APK.
import 'dart:convert';

import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:frontend/services/classifier.dart';
import 'package:integration_test/integration_test.dart';

void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  testWidgets('TFLite app and Python reference agree on fixed photos', (_) async {
    final raw = await rootBundle.loadString('assets/models/model_metadata.json');
    final metadata = jsonDecode(raw) as Map<String, dynamic>;
    expect(metadata['sha256'], _expectedSha, reason: 'Regenera la prueba para este TFLite.');
    final classifier = LocalClassifier();
    await classifier.load();
    for (final sample in _cases) {
      final result = await classifier.predict(base64Decode(sample.photo));
      expect(result.winner, sample.winner, reason: sample.name);
      for (var i = 0; i < 3; i++) {
        expect(result.scores[i], closeTo(sample.scores[i], _tolerance), reason: sample.name);
      }
    }
  });
}

class _Case {
  const _Case(this.name, this.photo, this.winner, this.scores);
  final String name;
  final String photo;
  final int winner;
  final List<double> scores;
}

"""


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--reference", type=Path, default=ROOT / "ml/artifacts/export_parity.json")
    p.add_argument("--samples", type=Path, default=ROOT / "ml/samples")
    p.add_argument("--models", type=Path, default=ROOT / "frontend/assets/models")
    p.add_argument("--tolerance", type=float, default=0.01)
    a = p.parse_args()
    if not 0 < a.tolerance <= 0.05:
        raise ValueError("Indica una tolerancia positiva de hasta 0,05.")
    rows = read_json(a.reference)
    if not rows:
        raise ValueError("No hay puntuaciones de referencia.")
    metadata = read_json(a.models / "model_metadata.json")
    checksum = sha256(a.models / "tomatolens_v1.tflite")
    if checksum != metadata["sha256"]:
        raise ValueError("El TFLite no coincide con su metadata.")
    ref_hash = metadata.get("parity_reference_sha256")
    if ref_hash is None:
        if (
            metadata["model_version"] != "legacy-v1"
            or a.reference.resolve() != ROOT / "ml/artifacts/export_parity.json"
        ):
            raise ValueError("El modelo requiere una referencia trazable.")
    elif ref_hash != sha256(a.reference):
        raise ValueError("La referencia no corresponde a esta exportación.")
    photos = {}
    for photo in a.samples.glob("*/*"):
        if not photo.is_file():
            continue
        if photo.name in photos:
            raise ValueError(f"Nombre de muestra repetido: {photo.name}")
        photos[photo.name] = photo
    code = [
        HEADER,
        f"const _expectedSha = '{checksum}';",
        f"const _tolerance = {a.tolerance};",
        "const _cases = <_Case>[",
    ]
    for row in rows:
        scores = row["scores"]
        if len(scores) != 3:
            raise ValueError("Cada referencia requiere tres puntuaciones.")
        photo = photos[row["file"]]
        if row.get("file_sha256") and row["file_sha256"] != sha256(photo):
            raise ValueError(f"La muestra cambió desde la exportación: {photo.name}")
        name = json.dumps(photo.name.replace("$", "_"), ensure_ascii=False)
        winner = max(range(3), key=scores.__getitem__)
        data = base64.b64encode(photo.read_bytes()).decode("ascii")
        code.extend(
            [
                f"  _Case({name},",
                *[f"    '{data[i : i + 72]}'" for i in range(0, len(data), 72)],
                f"    , {winner}, <double>{scores}),",
            ]
        )
    code.extend(["];", ""])
    out = ROOT / "frontend/integration_test/native_parity_generated_test.dart"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(code), encoding="utf-8")
    print(f"Prueba generada con {len(rows)} casos: {out}")


if __name__ == "__main__":
    main()
